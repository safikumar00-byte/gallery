// Helper to partition the projects into 6 columns for desktop layout
export function getGalleryColumns(projects: ProjectItem[], columnCount: number = 6): ProjectItem[][] {
  const columns: ProjectItem[][] = Array.from({ length: columnCount }, () => []);
  projects.forEach((item, index) => {
    columns[index % columnCount].push(item);
  });
  return columns;
}
